import assert from 'node:assert/strict';
const requests = [];
globalThis.window = { location: { href:'https://example.test/InfiniteUniverse/' }, requestIdleCallback: fn => queueMicrotask(fn), setTimeout };
Object.defineProperty(globalThis, 'navigator', { value:{ connection:{ saveData:false, effectiveType:'4g' } }, configurable:true });
globalThis.DOMParser = class { parseFromString() { return {}; } };
globalThis.fetch = async url => { requests.push(url); return { ok:true, text:async()=>'<p>test</p>' }; };
const { scheduleContentPrewarm } = await import('../scripts/content-cache.js');
const state = { language:'en', activeDomain:'physical-foundations', activeTopic:'probability-statistics' };
scheduleContentPrewarm(state);
await new Promise(resolve => setTimeout(resolve,20));
assert.ok(requests.length > 0 && requests.length <= 6);
assert.ok(requests.every(url=>url.includes('/en/')));
const count=requests.length;
scheduleContentPrewarm(state);
await new Promise(resolve => setTimeout(resolve,20));
assert.equal(requests.length,count,'Already warmed files are not fetched again');
navigator.connection.saveData=true;
scheduleContentPrewarm({...state,language:'es'});
await new Promise(resolve => setTimeout(resolve,20));
assert.equal(requests.length,count,'Data-saving mode disables prewarming');
console.log('Bounded, current-language, cached, data-saving prewarming passed.');
